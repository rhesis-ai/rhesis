"""The built-in role table in the docs is generated from the capability catalog.

This test fails when it drifts. To regenerate it::

    RHESIS_UPDATE_ROLE_DOCS=1 uv run pytest ../../tests/backend/ee/rbac/test_role_docs.py
"""

from __future__ import annotations

import os
import re
from collections import defaultdict
from pathlib import Path

from rhesis.backend.app.auth.capabilities import (
    SCOPE_ORGANIZATION,
    capability_scope,
    get_all_capabilities,
)
from rhesis.backend.ee.rbac.models import permissions_for_built_in_role

ROLES_DOC = Path(__file__).resolve().parents[4] / "docs/content/docs/organizations/roles.mdx"
START = "{/* role-matrix:start, generated by tests/backend/ee/rbac/test_role_docs.py */}"
END = "{/* role-matrix:end */}"
ROLES = ("Owner", "Admin", "Auditor", "Member", "Viewer")
WORDS = {"read": "view", "update": "edit", "execute": "run"}


def _action(action: str) -> str:
    verb, _, qualifier = action.partition(":")
    word = WORDS.get(verb, verb)
    return f"{word} {qualifier}" if qualifier else word


def _cell(actions: list[str], granted: set[str], resource: str) -> str:
    have = [a for a in actions if f"{resource}:{a}" in granted]
    if not have:
        return "–"
    if len(have) == len(actions):
        return "All"
    return ", ".join(dict.fromkeys(_action(a) for a in have))


def _table(resources: dict[str, list[str]], granted: dict[str, set[str]]) -> list[str]:
    lines = ["| Resource | " + " | ".join(ROLES) + " |", "|---" * (len(ROLES) + 1) + "|"]
    for resource, actions in sorted(resources.items()):
        cells = [_cell(actions, granted[role], resource) for role in ROLES]
        lines.append(f"| `{resource}` | " + " | ".join(cells) + " |")
    return lines


def render_matrix() -> str:
    from rhesis.backend.app.main import app  # noqa: F401  registers the route-derived capabilities

    catalog = sorted(get_all_capabilities())
    granted = {role: permissions_for_built_in_role(role, catalog) for role in ROLES}
    org: dict[str, list[str]] = defaultdict(list)
    project: dict[str, list[str]] = defaultdict(list)
    for capability in catalog:
        resource, _, action = capability.partition(":")
        scope = org if capability_scope(capability) == SCOPE_ORGANIZATION else project
        scope[resource].append(action)

    return "\n".join(
        [
            START,
            "",
            "**Organization-wide**",
            "",
            *_table(org, granted),
            "",
            "**Inside a project** (for Member and Viewer, in projects they belong to)",
            "",
            *_table(project, granted),
            "",
            END,
        ]
    )


def test_role_matrix_matches_the_catalog():
    doc = ROLES_DOC.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    assert pattern.search(doc), f"role matrix markers missing from {ROLES_DOC}"
    expected = render_matrix()

    if os.environ.get("RHESIS_UPDATE_ROLE_DOCS"):
        ROLES_DOC.write_text(pattern.sub(lambda _: expected, doc))
        return

    assert pattern.search(doc).group(0) == expected, (
        "The role table in roles.mdx is out of date. Regenerate it with "
        "RHESIS_UPDATE_ROLE_DOCS=1 (see this test's docstring)."
    )
